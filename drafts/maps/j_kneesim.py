# ── geometry helpers ──
def bez_split(p, t):
    """split a cubic (p0, p1, p2, p3) at t → (left, right)"""
    lerp = lambda a, b: (a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t)
    a, b, c, d = p
    ab, bc, cd = lerp(a, b), lerp(b, c), lerp(c, d)
    abc, bcd = lerp(ab, bc), lerp(bc, cd)
    m = lerp(abc, bcd)
    return (a, ab, abc, m), (m, bcd, cd, d)
def cpath(p):
    r = lambda q: f'{round(q[0])} {round(q[1])}'
    return f'M{r(p[0])} C{r(p[1])} {r(p[2])} {r(p[3])}'
def rot(q, c, deg):
    a = math.radians(deg); x, y = q[0] - c[0], q[1] - c[1]
    return (c[0] + x * math.cos(a) - y * math.sin(a), c[1] + x * math.sin(a) + y * math.cos(a))
def stumps(p):
    """a torn ligament: the femoral and the tibial stump, with a gap"""
    left, rest = bez_split(p, 0.42)
    _, right = bez_split(p, 0.58)
    return left, right

